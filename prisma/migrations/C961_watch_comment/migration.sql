-- =====================================================================
-- C961 — 감시 뷰 문구 표준화
--
--   감시 뷰는 설명에 '0이어야' 가 들어 있는지로 찾습니다.
--   그런데 두 뷰는 문구가 달라 목록에서 빠져 있었습니다.
--
--     v_assumed_on        "오픈 전 반드시 0"
--     v_broker_gate_leak  "관을 열기 전에 반드시 0 이어야"
--
--   둘 다 실제 감시 대상입니다. 특히 v_assumed_on 은 지금 3건이라
--   목록에서 빠진 탓에 "이상 없음" 으로 보고돼 왔습니다.
--
--   뜻은 그대로 두고 표준 문구만 넣습니다. 감시 뷰 64 → 66.
-- =====================================================================

COMMENT ON VIEW public.v_assumed_on IS
'켜져 있는 간주 모드. **0이어야 오픈할 수 있습니다** — 결제 · 중개사 · 계좌가 모두 실제로 연결돼야 합니다. 연동을 마치면 assume.* 를 off 로 바꾸십시오.';

COMMENT ON VIEW public.v_broker_gate_leak IS
'중개사 인증도 등기부 확인도 없이 올라간 부동산. **0이어야 관을 열 수 있습니다** — 무등록 중개가 됩니다.';
