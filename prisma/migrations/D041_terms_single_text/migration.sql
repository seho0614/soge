② 다만 회사의 **고의나 중대한 과실**로 회원에게 손해가 생긴 경우에는
   책임을 집니다.
③ 회사는 등록물의 내용을 확인하지만, 그 확인이 **내용의 진실성을
   보증하는 것은 아닙니다.**

