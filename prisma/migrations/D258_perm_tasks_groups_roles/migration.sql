/* ── ① 업무별 권한 표 (v10.441 · docs/578) ──────────────────────────────────────
 *   대표 11/19 22:10 「업무 권한 업무별로 관리 · 권한그룹 · 개인권한(업무용 · 관리자) · 권한 관리는 SUPER」 승인 · 수준 4단계.
 *   업무 = 운영 화면 탭 하나 · 업무그룹 = 메뉴 그룹(처음) · 권한그룹 = 업무 × 수준 꾸러미 · 개인권한 = 그룹 붙이기 + 개별 더하기/빼기 + 기한.
 *   기존 역할(account_roles · @Roles)은 그대로 — 권한그룹은 그 안에서 더 좁힘(둘 다 통과해야 함). SUPER 는 늘 모든 권한.
 * ------------------------------------------------------------------------------- */
CREATE TABLE IF NOT EXISTS public.perm_task_groups (
  key         text PRIMARY KEY CHECK (key ~ '^[a-z][a-z0-9_]{1,30}$'),
  name        text NOT NULL CHECK (char_length(btrim(name)) BETWEEN 1 AND 40),
  sort        integer NOT NULL DEFAULT 0,
  updated_by  uuid REFERENCES public.accounts(id),
  updated_at  timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE public.perm_task_groups IS 'v10.441 (D258) 업무그룹 — 처음은 운영 화면 메뉴 그룹과 같음 · SUPER 가 이름 · 순서만 고침';

CREATE TABLE IF NOT EXISTS public.perm_tasks (
  key         text PRIMARY KEY CHECK (key ~ '^[a-z][a-z0-9-]{1,40}$'),
  name        text NOT NULL CHECK (char_length(btrim(name)) BETWEEN 1 AND 60),
  group_key   text NOT NULL REFERENCES public.perm_task_groups(key),
  levels      text[] NOT NULL DEFAULT ARRAY['VIEW','EDIT','APPROVE','EXPORT'] CHECK (levels <@ ARRAY['VIEW','EDIT','APPROVE','EXPORT']),
  sort        integer NOT NULL DEFAULT 0,
  active      boolean NOT NULL DEFAULT true
);
COMMENT ON TABLE public.perm_tasks IS 'v10.441 (D258) 업무 — 운영 화면 탭 하나 = 업무 하나(key = 탭 key) · 쓸 수 있는 수준(VIEW · EDIT · APPROVE · EXPORT)';

CREATE TABLE IF NOT EXISTS public.perm_role_groups (
  key         text PRIMARY KEY CHECK (key ~ '^[A-Z][A-Z0-9_]{1,40}$'),
  name        text NOT NULL CHECK (char_length(btrim(name)) BETWEEN 1 AND 40),
  kind        text NOT NULL DEFAULT 'STAFF' CHECK (kind IN ('STAFF', 'MANAGER')),
  from_role   text,
  note        text CHECK (note IS NULL OR char_length(note) <= 200),
  active      boolean NOT NULL DEFAULT true,
  created_by  uuid REFERENCES public.accounts(id),
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE public.perm_role_groups IS 'v10.441 (D258) 권한그룹 — 직무 꾸러미(업무 × 수준) · STAFF 업무용 · MANAGER 관리자 · from_role 이 있으면 처음 변환으로 만든 것(그 역할을 받으면 저절로 붙음)';

CREATE TABLE IF NOT EXISTS public.perm_role_group_items (
  group_key   text NOT NULL REFERENCES public.perm_role_groups(key),
  task_key    text NOT NULL REFERENCES public.perm_tasks(key),
  level       text NOT NULL CHECK (level IN ('VIEW', 'EDIT', 'APPROVE', 'EXPORT')),
  PRIMARY KEY (group_key, task_key, level)
);

CREATE TABLE IF NOT EXISTS public.perm_account_groups (
  account_id  uuid NOT NULL REFERENCES public.accounts(id),
  group_key   text NOT NULL REFERENCES public.perm_role_groups(key),
  expires_at  timestamptz,
  granted_by  uuid REFERENCES public.accounts(id),
  granted_at  timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (account_id, group_key)
);
CREATE TABLE IF NOT EXISTS public.perm_account_overrides (
  id          bigserial PRIMARY KEY,
  account_id  uuid NOT NULL REFERENCES public.accounts(id),
  task_key    text NOT NULL REFERENCES public.perm_tasks(key),
  level       text NOT NULL CHECK (level IN ('VIEW', 'EDIT', 'APPROVE', 'EXPORT')),
  effect      text NOT NULL CHECK (effect IN ('ALLOW', 'DENY')),
  expires_at  timestamptz,
  reason      text NOT NULL CHECK (char_length(btrim(reason)) BETWEEN 2 AND 200),
  granted_by  uuid REFERENCES public.accounts(id),
  created_at  timestamptz NOT NULL DEFAULT now(),
  UNIQUE (account_id, task_key, level)
);
CREATE TABLE IF NOT EXISTS public.perm_account_kind (
  account_id  uuid PRIMARY KEY REFERENCES public.accounts(id),
  kind        text NOT NULL CHECK (kind IN ('STAFF', 'MANAGER')),
  updated_by  uuid REFERENCES public.accounts(id),
  updated_at  timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE public.perm_account_kind IS 'v10.441 (D258) 사람 구분 — STAFF 업무용 · MANAGER 관리자(관리자 권한그룹은 MANAGER 에게만 붙임)';

