/* 관리자(MANAGER) 권한그룹은 MANAGER 구분인 사람에게만 */
CREATE OR REPLACE FUNCTION public.fn_perm_account_group_guard() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v_gk text;
BEGIN
  SELECT kind INTO v_gk FROM public.perm_role_groups WHERE key = NEW.group_key;
  IF v_gk = 'MANAGER' AND NOT EXISTS (SELECT 1 FROM public.perm_account_kind k WHERE k.account_id = NEW.account_id AND k.kind = 'MANAGER') THEN
    RAISE EXCEPTION 'PERM_KIND: 관리자 권한그룹은 관리자 구분인 사람에게만 붙입니다.';
  END IF;
  RETURN NEW;
END $$;
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname = 'trg_perm_account_group_guard' AND tgrelid = 'public.perm_account_groups'::regclass) THEN
    CREATE TRIGGER trg_perm_account_group_guard BEFORE INSERT OR UPDATE ON public.perm_account_groups FOR EACH ROW EXECUTE FUNCTION public.fn_perm_account_group_guard();
  END IF;
END $$;

/* 한 사람의 지금 권한(업무 · 수준) — 그룹(기한 안) ∪ 개별 더하기 − 개별 빼기 */
CREATE OR REPLACE FUNCTION public.fn_perm_effective(p_account uuid)
 RETURNS TABLE (task_key text, level text) LANGUAGE sql STABLE AS $$
  SELECT x.task_key, x.level FROM (
    SELECT i.task_key, i.level
      FROM public.perm_account_groups g JOIN public.perm_role_groups r ON r.key = g.group_key AND r.active
      JOIN public.perm_role_group_items i ON i.group_key = g.group_key
     WHERE g.account_id = p_account AND (g.expires_at IS NULL OR g.expires_at > now())
    UNION
    SELECT o.task_key, o.level FROM public.perm_account_overrides o
     WHERE o.account_id = p_account AND o.effect = 'ALLOW' AND (o.expires_at IS NULL OR o.expires_at > now())
  ) x
  WHERE NOT EXISTS (SELECT 1 FROM public.perm_account_overrides d
                     WHERE d.account_id = p_account AND d.effect = 'DENY' AND d.task_key = x.task_key AND d.level = x.level
                       AND (d.expires_at IS NULL OR d.expires_at > now()))
$$;

