CREATE OR REPLACE FUNCTION public.fn_perm_role_attach() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF coalesce((SELECT value FROM public.site_settings WHERE key = 'perm.auto_role_group'), 'on') <> 'on' THEN RETURN NEW; END IF;
  IF NOT EXISTS (SELECT 1 FROM public.perm_role_groups WHERE key = 'R_' || NEW.role) THEN RETURN NEW; END IF;
  /* 붙이기가 어떤 까닭으로 막혀도 역할 주기는 그대로(권한그룹은 SUPER 가 화면에서 다시 붙임) */
  BEGIN
    INSERT INTO public.perm_account_kind (account_id, kind) VALUES (NEW.account_id, CASE WHEN NEW.role = 'ADMIN' THEN 'MANAGER' ELSE 'STAFF' END)
    ON CONFLICT (account_id) DO UPDATE SET kind = 'MANAGER' WHERE NEW.role = 'ADMIN';
    INSERT INTO public.perm_account_groups (account_id, group_key, expires_at) VALUES (NEW.account_id, 'R_' || NEW.role, NEW.expires_at)
    ON CONFLICT (account_id, group_key) DO UPDATE SET expires_at = EXCLUDED.expires_at;   -- 다시 준 역할 · 늘린 기한과 맞춤
  EXCEPTION WHEN OTHERS THEN
    RAISE WARNING USING MESSAGE = 'perm attach skipped ' || SQLERRM;
  END;
  RETURN NEW;
END $$;
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname = 'trg_perm_role_attach' AND tgrelid = 'public.account_roles'::regclass) THEN
    CREATE TRIGGER trg_perm_role_attach AFTER INSERT ON public.account_roles FOR EACH ROW EXECUTE FUNCTION public.fn_perm_role_attach();
  END IF;
END $$;

/* 보안 점검(11/19) — 역할을 빼면 처음 변환 권한그룹(R_역할)도 뺌 · 역할 기한을 바꾸면 R_역할 기한도 맞춤
 *   (빼지 않으면 넓히기를 켰을 때 뺏긴 역할 범위로 계속 들어올 수 있음) · 예외는 삼켜 역할 빼기 · 고치기를 막지 않음 */
CREATE OR REPLACE FUNCTION public.fn_perm_role_detach() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  BEGIN
    DELETE FROM public.perm_account_groups WHERE account_id = OLD.account_id AND group_key = 'R_' || OLD.role;
  EXCEPTION WHEN OTHERS THEN
    RAISE WARNING USING MESSAGE = 'perm detach skipped ' || SQLERRM;
  END;
  RETURN OLD;
END $$;
CREATE OR REPLACE FUNCTION public.fn_perm_role_expiry() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.expires_at IS DISTINCT FROM OLD.expires_at THEN
    BEGIN
      UPDATE public.perm_account_groups SET expires_at = NEW.expires_at WHERE account_id = NEW.account_id AND group_key = 'R_' || NEW.role;
    EXCEPTION WHEN OTHERS THEN
      RAISE WARNING USING MESSAGE = 'perm expiry skipped ' || SQLERRM;
    END;
  END IF;
  RETURN NEW;
END $$;
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname = 'trg_perm_role_detach' AND tgrelid = 'public.account_roles'::regclass) THEN
    CREATE TRIGGER trg_perm_role_detach AFTER DELETE ON public.account_roles FOR EACH ROW EXECUTE FUNCTION public.fn_perm_role_detach();
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname = 'trg_perm_role_expiry' AND tgrelid = 'public.account_roles'::regclass) THEN
    CREATE TRIGGER trg_perm_role_expiry AFTER UPDATE OF expires_at ON public.account_roles FOR EACH ROW EXECUTE FUNCTION public.fn_perm_role_expiry();
  END IF;
END $$;
/* 이미 역할이 없는데 남은 R_역할(처음 변환 뒤 역할을 뺀 경우) 정리 — 다시 돌려도 같음 */
