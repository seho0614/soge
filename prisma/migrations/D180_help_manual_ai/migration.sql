## 2. 가입 · 로그인 · 비밀번호 · 탈퇴

### 2-1. 회원가입 (`/signup`)
1. 「무료 회원가입」을 누르고 가입 유형을 고릅니다: **개인 회원 · 개인 사업자 · 법인 사업자**. 어느 유형이든 하는 업무는 같습니다.
2. 사업자는 사업자등록번호(법인은 법인등록번호도)를 조회합니다. 휴업 · 폐업 사업자는 사업자로 가입할 수 없고, 사업자당 계정은 1개입니다.
3. 이름(실명) · 이메일 · 비밀번호를 넣습니다. 이메일이 로그인 아이디입니다. 비밀번호는 **영문 · 숫자 · 특수문자를 섞어 10자 이상**입니다.
4. 약관에 동의합니다. 필수 항목에 모두 동의해야 넘어갑니다. 선택 항목(마케팅 · 맞춤형 광고 등)은 나중에 바꿀 수 있습니다.
5. 관심 성향(선택)은 건너뛰어도 가입됩니다.
- 개인 회원은 **바로 가입**됩니다. 사업자 인증은 운영자 확인 뒤 끝나며, 그 전에도 본인인증만으로 모든 업무를 할 수 있습니다.
- "지금은 새 가입을 잠시 받지 않습니다"가 보이면 잠시 뒤 다시 시도하세요. 이미 가입한 분은 로그인할 수 있습니다.

### 2-2. 본인인증 · 사업자 인증 (`/verify`)
- **본인인증**은 사람을 확인합니다. 문의하기 · 매물 등록 · 거래 참여 · 소개비 받기에 필요합니다. 정산 때 예금주명과 대조하므로 실명이어야 합니다.
- 휴대폰 본인확인 연동은 **준비 중**입니다. 화면에 "연동 준비 중"이 보이면 실제 확인이 이루어진 것이 아닙니다. 막히면 고객센터로 문의해 주세요.
- **사업자 인증은 선택**입니다. 사업자로 소개비(세금계산서)를 받을 때만 필요하고, 인증이 끝난 시각 뒤에 성사된 거래부터 적용됩니다(소급 없음). 「나의공간 › 사업자 전환」(`/my/business`)에서 신청합니다.

### 2-3. 로그인 (`/login`)
- 이메일과 비밀번호로 로그인합니다. 「로그인 상태 유지」를 고를 수 있습니다.
- 비밀번호를 **5번 틀리면 30분 동안 잠깁니다**. 30분 뒤 다시 시도하거나 비밀번호를 재설정하세요.
- 약관이 바뀐 뒤 로그인하면 약관 동의 화면(`/terms/agree`)으로 갑니다. 바뀐 점을 보고 필수 약관에 동의하면 가려던 화면으로 이어집니다.
- 가입한 이메일이 기억나지 않으면 로그인 화면 「이메일 찾기」 → 고객센터 「계정」 문의로 알려 주세요. 본인 확인 뒤 도와 드립니다.

### 2-4. 비밀번호 찾기 · 바꾸기
- 잊었을 때: 「비밀번호 찾기」(`/login/forgot`)에서 이메일을 넣으면 재설정 링크를 보냅니다. 링크는 **30분 동안 한 번만** 쓸 수 있습니다.
- 메일이 오지 않으면 스팸함을 확인하세요. 메일 발송이 준비 중이라 보낼 수 없다는 안내가 나오면 고객센터 「계정」 문의로 알려 주세요.
- 알 때: 「나의공간 › 프로필 · 사업자 정보」(`/my/account`) › 비밀번호 변경.
- 비밀번호를 바꾸면 **다른 기기의 로그인이 모두 풀립니다**.

### 2-5. 회원 탈퇴 (`/my/account/withdraw`)
- 「나의공간 › 프로필 · 사업자 정보 › 회원 탈퇴」에서 합니다. 탈퇴 사유 · 지금 비밀번호 · 확인란이 필요합니다.
- 진행 중인 거래 · 정산 · 주문이 있으면 그것이 끝나야 탈퇴할 수 있습니다. 화면에 남은 일과 「보러 가기」가 나옵니다.
- 탈퇴하면 올린 매물 · 요청이 바로 내려가고 발급한 소개코드가 멈춥니다. 유료 구독은 자동 결제가 멈추고, 파트너 활동도 함께 끝납니다.
- 거래 기록이 있으면 관련 법령에 따라 일정 기간 보관한 뒤 파기하며, 그동안에도 로그인할 수 없습니다. 거래 기록이 없으면 회원 정보를 바로 파기합니다. 자세한 기준은 약관 · 개인정보처리방침을 보세요.
- 같은 이메일로 다시 가입하려면 파기가 끝난 뒤에 할 수 있습니다. **탈퇴는 되돌릴 수 없습니다.**

