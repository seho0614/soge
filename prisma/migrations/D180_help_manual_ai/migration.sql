## 7. 파트너 · 제휴 · 소개몰 입점

### 7-1. 머리줄 아이콘의 뜻
로그인하면 자격에 따라 머리줄 오른쪽에 아이콘이 보입니다. 마우스를 올리면 이름이 나옵니다.

| 아이콘 | 이름 | 누가 보나 | 가는 곳 |
|---|---|---|---|
| 방패 | 관리자 페이지 | 운영자만 | 운영 화면 |
| 집 | 안심소개 파트너 | 안심소개 파트너(심사 중 포함) | `/partner` |
| 두 사람 | 파트너센터 | 제휴 파트너로 활동 중인 회원 | `/partners` |
| 가게 | 소개몰 입점 신청 / 소개몰 판매자센터 | 입점 신청이 열려 있을 때 로그인한 회원 | `/health/seller` · 입점한 판매자는 `/health/seller/center` |

- 자격이 없으면 아이콘이 보이지 않습니다. 「파트너센터」는 글자 링크로 보입니다.
- 휴대폰(좁은 화면)에서는 아이콘 대신 메뉴 끝에 글자로 나옵니다.

### 7-2. 안심소개 파트너(입점 업체) 신청 (`/partner/apply`)
- 안심소개에서 상담 · 매물을 받는 업체용입니다. 본인인증을 하면 **개인으로도** 신청할 수 있고, 사업자 인증은 선택입니다.
- 순서: 본인 · 사업자 확인 → 업종 · 지역 선택 → 운영 승인. 자동 승인은 없고 사람이 확인합니다(접수 안내에 결과 예정이 표시됨).
- 반려되면 사유를 알림으로 보내 드리며, 고쳐서 다시 신청할 수 있습니다.

### 7-3. 제휴 파트너 (`/partners`)
- 제휴상품 링크를 퍼뜨리고, 링크로 들어온 주문이 확정되면 건당 정해진 수수료를 소개뱅크가 지급하는 제도입니다. 안심소개 파트너 신청과는 **따로**입니다.
- 본인인증을 하면 개인으로 신청할 수 있습니다. 운영이 직접 확인 뒤 승인합니다. 처음이면 「파트너가이드」(`/partners/guides`)를 먼저 보세요.
- 제휴 링크는 마지막 클릭 기준 72시간 안의 주문이 인정됩니다. 소개코드(90일 첫 유입)와는 다른 규칙입니다.
- 수수료 지급 계좌는 1원 입금으로 확인하며, 인증 전에는 지급되지 않습니다. 소개몰 주문이 열리기 전에는 수익이 생기지 않습니다.

### 7-4. 소개몰 입점 신청 (`/health/seller`)
- 소개몰에 상품을 팔고 싶은 회원이 신청합니다. **운영이 입점 신청을 열었을 때만** 가게 아이콘과 신청 화면이 보입니다.
- 신청할 때 입점 약관 동의가 필요하고, 운영이 심사합니다.
- 실제 판매와 판매대금 지급은 결제 연동이 끝난 뒤 시작됩니다. 그 전에는 신청 · 심사까지만 됩니다.

