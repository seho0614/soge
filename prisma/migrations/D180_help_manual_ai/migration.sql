### 8-2. 분쟁 접수 (`/support/dispute`)
- 거래 분쟁은 일반 문의가 아니라 「분쟁 접수」로 해야 합니다. 접수하면 그 거래의 정산이 보류되고, 처리가 끝나면 풀립니다.

### 8-3. 사기 예방 (`/safety/guide`)
