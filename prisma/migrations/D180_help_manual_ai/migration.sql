## 4. 소개장터 · 매물 · 요청 · 소개코드 · 거래

### 4-1. 매물 찾기
- 머리줄에서 관(소개장터 · 안심소개 · 소개창업)을 고르거나 `/search` 에서 검색합니다. 열람과 검색은 로그인 없이도 됩니다.
- 목록 · 상세에는 지역이 시 · 구까지만 보입니다. 상세주소는 등록자 본인과 운영만 봅니다.
- 「광고」 표시가 붙은 것은 광고이며 추천 순위 계산에는 들어가지 않습니다.
- 마음에 드는 매물은 관심 목록에 담을 수 있습니다(`/my/likes`).

### 4-2. 매물 올리기 (`/register`)
- 로그인과 **본인인증**이 필요합니다. 개인 회원도 소개장터 · 안심소개 · 소개창업 모두에 올릴 수 있습니다.
- 관과 업종을 고르고 제목(5자 이상) · 내용 · 사진 · 지역을 적습니다. 업종에 따라 등급이 정해지며, 최종 확정은 운영자 검수입니다.
- 등록하면 **검수**를 거쳐 노출됩니다. 검수 승인 전에는 어디에도 보이지 않습니다. 일부는 자동 승인되고, 첫 등록 등은 담당자가 확인합니다.
- 검수가 오래 걸리면 고객센터 1:1 문의로 알려 주세요.
- 고치기는 「나의공간 › 내 등록 리스팅」에서 합니다. 고치면 다시 검수를 받습니다.
- 급하게 사거나 팔아야 하면 매물을 올린 뒤 내 매물에서 「급구 · 급매」를 신청하세요(운영 심사 · 기한이 지나면 자동 해제).
- 자격이 필요한 업종: 부동산은 「나의공간 › 중개사 인증」(`/my/broker`) 등 인증 뒤, 보험 · 의료는 자격 심사 승인 뒤 등록됩니다. 다단계 · 대부 · 사행성 등 제한 업종은 올릴 수 없습니다.
- 안심소개 부동산은 소개비가 아니라 노출료 방식입니다. 소개뱅크는 중개보수를 받지 않습니다.

### 4-3. 소개받기 — 필요한 것 요청하기 (`/request`)
- 필요한 물품 · 용역 · 부동산 · 장비 · 창업 공간을 올리면 소개자가 제안합니다. 올리기는 `/request/new` 입니다.
- 요청한 분이 공개 범위를 정할 수 있고, 회사명을 감출 수 있습니다.
- 요청은 등록 후 **30일**이 지나면 자동으로 닫힙니다.
- 「예상 소개비」는 요청자가 적은 희망 금액이며, 최종 금액은 대화에서 정합니다.
- 제안하기: 로그인 + 본인인증 뒤, 요청 상세에서 소개할 업체 · 관계 · 제안 내용(10자 이상)을 보냅니다. 요청 1건에 한 번만 제안할 수 있고, 제안은 요청자에게만 보입니다.
- 요청자가 「수락하고 대화 시작」을 누르면 1:1 대화가 열립니다. 거절한 제안은 되돌릴 수 없습니다.
- 요청 열람 · 제안 횟수에는 요금제별 한도가 있을 수 있습니다(화면에 표시).

### 4-4. 소개코드
- 소개코드는 **매물마다 따로** 받습니다. 소개할 매물 상세에서 「소개코드 공유」를 누르고 링크를 복사해 보내세요. 같은 매물은 다시 눌러도 같은 코드입니다.
- 상대가 내 링크로 들어와 **90일 안에** 그 매물에 문의하면 소개자로 기록됩니다. 처음 들어온 소개코드가 90일 동안 유지되며, 뒤에 다른 코드로 들어와도 바뀌지 않습니다.
- 귀속은 1:1 대화가 시작될 때 확정됩니다. 전화 등 사이트 밖에서만 진행하면 기록되지 않습니다.
- 받을 수 없는 경우: 본인 매물, 게시 중이 아닌 매물, 보험 · 의료 매물(법령상 소개 대가 금지).
- 본인인증 뒤에 받을 수 있습니다. **무료(베이직) 요금제에는 무료 소개코드가 없고**, 유료 요금제는 월 포함 건수까지 무료입니다. 넘으면 건당 추가 결제 뒤 발급됩니다. 요금제 금액 · 추가 발급 비용은 「구독 · 소개코드」(`/my/subscription`) 화면 표시를 따릅니다.
- **결제 연동은 준비 중**입니다. "시험 결제"로 표시되는 결제는 실제 돈이 오가지 않습니다.

### 4-5. 문의 · 1:1 대화
- 매물 상세의 「문의하기」를 누르면 등록자와 1:1 대화가 열립니다. 로그인과 본인인증이 필요합니다.
- 대화 목록은 「나의공간 › 문의 · 대화」(`/my/inquiries`)에 있습니다.
- 대화는 소개뱅크 대화방 안에서 하세요. 기록이 분쟁 근거로 남습니다.

### 4-6. 거래 진행: 계약 → 대금 → 성사 확정
1. **조건 협의**: 1:1 대화에서 조건을 맞춘 뒤 「계약서 요청하기」를 누릅니다.
2. **계약서**: 표준계약서 양식의 빈칸만 채웁니다(조항은 고칠 수 없음). 조건 합의 → 양측 서명 순서이며, 한쪽이 조건을 바꾸면 상대의 합의를 다시 받아야 합니다. 서명 뒤에는 바꿀 수 없어 파기 후 다시 맺어야 합니다. 전자서명 연동은 준비 중입니다. 진행은 「나의공간 › 계약 진행」(`/my/contracts`).
3. **결제 · 대금**: 대금은 당사자끼리 직접 주고받고, 화면에서는 지급 사실만 신고합니다. 대금은 계약 상대 명의 계좌로만 보내세요.
4. **성사 확정**: 양측이 **각각** 눌러야 성사됩니다. 한쪽만 눌러서는 넘어가지 않습니다.
5. **후기**: 성사 뒤 후기를 쓸 수 있습니다.
- 소개뱅크는 양식만 제공하며 계약 당사자가 아닙니다. 조건과 이행 책임은 당사자에게 있습니다.

### 4-7. 정산 · 소개비 받기 (`/my/settlement`)
- 본인인증 회원이면 개인도 소개비를 받습니다. 사업자 인증을 하면 사업자로 받고, 세금계산서는 소개자가 직접 발행합니다.
- 성사가 확정된 건만 정산을 신청할 수 있습니다. 순서: 승인 대기 → 승인됨 · 지급 대기 → 소개비를 받으면 「받았음 표시」(지급 완료).
- **소개비는 거래 당사자가 직접 지급합니다.** 소개뱅크는 소개비를 대신 받거나 보내지 않으며, 소개비에서 떼는 금액도 없습니다.
- 받을 계좌는 본인 명의여야 하며 1원 입금으로 확인합니다. 계좌 확인 연동은 준비 중입니다. 확인 코드를 다섯 번 틀려 막히면 고객센터로 연락 주세요.
- 소개비는 받는 분의 소득이므로 세금 신고는 받는 분이 합니다.
- 화면에 "소개비 기능은 아직 열리지 않았습니다"가 보이면 연동 준비 중이라는 뜻입니다.
- 분쟁을 접수하면 그 거래의 정산이 보류되고, 처리가 끝나면 풀립니다.

### 4-8. 구독 · 요금제 (`/my/subscription`)
- 개인도 구독할 수 있습니다. 현재 요금제 · 남은 소개코드는 「구독 · 소개코드」, 열람 · 슬롯 한도는 「한도 안내 · 요금제」(`/my/subscription/upgrade`)에서 봅니다.
- 요금제 금액은 화면 표시를 따르며 바뀔 수 있습니다. **정기결제 연동은 준비 중**입니다. 결제 카드 등록은 「결제 수단」(`/my/payment`).

