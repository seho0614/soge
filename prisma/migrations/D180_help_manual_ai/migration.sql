- 돈 피해가 났다면 경찰(112) · 경찰청 사이버범죄 신고시스템에도 함께 신고하세요. 대화 · 계약 기록은 소개뱅크가 보존합니다.

### 8-4. 약관 보기 (`/terms`)
- 「약관 · 법적 고지」에서 이용약관 · 개인정보처리방침 · 환불 정책 등을 봅니다. 문서 이름을 누르면 판 번호 · 시행일과 함께 전문(`/terms/[문서]`)이 열립니다. 바닥줄 링크로도 갈 수 있습니다.
- 약관이 바뀌면 시행일 전에 알림으로 알려 드리고, 필수 약관은 시행일부터 다시 동의를 받습니다.
- 선택 동의(마케팅 · 맞춤형 광고 등)는 약관 동의 화면(`/terms/agree`)의 「선택 항목 바꾸기」에서 언제든 바꿀 수 있습니다. 필수 약관 동의는 탈퇴로만 철회됩니다.

