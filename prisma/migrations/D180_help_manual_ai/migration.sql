## 1. 소개뱅크는 어떤 곳인가요

### 1-1. 소개뱅크 한눈에 보기
- 소개뱅크는 **소개하고 소개비를 받는 곳**입니다. 아는 상품 · 서비스 · 매물 · 사업 기회를 필요한 사람에게 소개하고, 거래가 성사되면 당사자끼리 정한 소개비를 받습니다.
- 소개뱅크는 회원끼리 직접 거래하는 **개인 간(P2P) 서비스**입니다. 개인 회원도 본인인증을 하면 모든 업무를 할 수 있습니다. 등록에 자격이 필요한 업종(공인중개사 · 보험 · 의료 등)만 그 자격 확인을 받은 뒤 등록합니다.
- 소개비 금액은 정해진 요율표가 없고 **당사자끼리 협의**해서 정합니다. 소개뱅크는 소개비에서 **아무것도 떼지 않습니다**.
- 소개뱅크는 거래 대금을 **받지도 보관하지도 않습니다**. 대금은 당사자끼리 직접 주고받습니다. 소개뱅크 계좌로 돈을 보내라는 요구는 사기입니다.
- 운영: (주)한국바이오헬스케어 소개뱅크 사업부. 소개몰은 소개뱅크가 직접 파는 직판(통신판매업자)이고, 나머지 관은 회원 사이 거래를 돕는 통신판매중개자입니다. 사업자 정보는 화면 맨 아래 바닥줄에 있습니다.

### 1-2. 관(서비스 묶음) 구성
화면 위 머리줄 메뉴는 다음 순서입니다.

| 메뉴 | 주소 | 다루는 것 |
|---|---|---|
| 소개장터 | `/money` | 상품 · 서비스 소개. 급구 · 급매, 베스트매칭, 이벤트 포함 |
| 안심소개 | `/mall` | 인증이 필요한 거래 — 기계 · 설비 · 시설 / 부동산 / 생활 · 금융 상담 |
| 소개창업 | `/biz` | 창업 · 가맹 · 점포 양수도, 인력(도급), 운영지원, 정보 |
| 소개몰 | `/health` | 건강 상품 쇼핑몰(직판) |
| 소개광장 | `/community` | 소개 후기 · 업종 이야기 · 질문 · 「이건 어때?」 투표 · 우리동네 맛집 |
| 이용안내 | `/guide` | 이용 흐름 · 자주 묻는 것 · 약관 목록 |

- 필요한 것을 올려 소개를 받는 「소개받기」는 `/request` 입니다.
- 통합 검색은 `/search` 입니다. 두 글자 이상 넣으세요. 「문장으로 찾기」에 "10평 이내 상가 급매 있어?"처럼 문장으로 써도 됩니다.
- 화면 오른쪽 위 🌐 단추로 한국어 · 영어를 바꿀 수 있습니다. 약관은 한국어판이 우선합니다.

