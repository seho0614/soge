## 3. 내 정보 · 나의공간

### 3-1. 나의공간 (`/my`)
머리줄 「나의공간」을 누르면 진행 중 소개 · 성사 · 정산 대기 · 누적 수익과 아래 메뉴가 보입니다.

| 메뉴 | 주소 | 내용 |
|---|---|---|
| 내 등록 리스팅 | `/my/listings` | 등록한 상품 · 서비스와 노출 상태 |
| 소개 내역 | `/my/deals` | 내가 소개한 건과 귀속 코드 |
| 계약 진행 | `/my/contracts` | 당사자끼리 맺는 계약 |
| 문의 · 대화 | `/my/inquiries` | 진행 중인 1:1 대화 |
| 정산 · 지급 | `/my/settlement` | 소개비 정산 신청 · 지급 내역 |
| 관심 목록 | `/my/likes` | 담아 둔 상품 · 서비스 |
| 구독 · 소개코드 | `/my/subscription` | 요금제와 남은 소개코드 |
| 중개사 인증 | `/my/broker` | 부동산 등록 전 공인중개사 인증 |
| 알림 | `/my/notifications` | 거래 · 정산 · 검수 소식 |
| 사업자 전환 | `/my/business` | 사업자로 소개비 받기 |
| 소개 활동 | `/my/intro` | 초대 · 활동 · 포인트 |
| 프로필 · 사업자 정보 | `/my/account` | 이름 · 연락처 · 비밀번호 · 탈퇴 · 개인정보 · 보안 |
| 소개몰 주문 · 취소 · 반품 · 배송지 | `/my/health/...` | 소개몰 이용 내역 |

- 이메일은 로그인 수단이라 프로필에서 바로 바꿀 수 없습니다. 바꾸려면 고객센터로 문의해 주세요.
- 본인인증 뒤 이름을 바꾸면 다시 인증해야 합니다. 인증이 끝난 사업자 정보는 고칠 수 없고 「사업자 정보 다시 인증」으로 바꿉니다.

### 3-2. 로그인 기록 확인 (`/my/account/security`)
- 「나의공간 › 프로필 · 사업자 정보 › 개인정보 · 보안 › 로그인 기록 · 보안」에서 봅니다.
- 최근 로그인 30건의 때 · 결과(로그인 / 비밀번호 틀림) · IP 앞 두 자리 · 브라우저 종류가 나옵니다.
- 지난 7일 비밀번호가 틀린 기록이 있으면 경고가 뜹니다. 직접 한 것이 아니면 **비밀번호를 바꾸고 「모든 기기에서 로그아웃」**을 누르세요.
- 로그인 기록은 정해진 기간 보관한 뒤 지웁니다(기간은 화면에 표시).

### 3-3. 모든 기기에서 로그아웃
- 같은 화면(`/my/account/security`) 아래 「모든 기기에서 로그아웃」에서 지금 비밀번호를 넣고 누릅니다.
- 다른 휴대폰 · 컴퓨터에 남은 로그인이 모두 풀리고, **지금 쓰는 기기는 그대로** 쓸 수 있습니다.
- 기기를 하나씩 골라 로그아웃하는 기능은 없습니다.

### 3-4. 내 정보 내려받기 (`/my/account/data`)
- 소개뱅크가 보관한 내 정보를 **JSON 파일 하나**로 받습니다. 지금 비밀번호를 넣고 「내 정보 내려받기」를 누르세요.
- 들어가는 것: 프로필 · 약관 동의 · 매물 · 요청 · 소개코드 · 소개비 · 소개광장 글 · 댓글 · 투표 · 관심 목록 · 동네 · 소개몰 주문 · 반품 · 배송지 · 포인트 · 알림 · 문의 · 권리 요청 · 로그인 기록.
- 다른 회원의 이름 · 연락처, 운영 내부 메모, 비밀번호는 들어 있지 않습니다.
- 하루에 받을 수 있는 횟수가 정해져 있습니다(남은 횟수는 화면에 표시). 다 쓰면 다음 날 받으세요.
- 파일은 메모장이나 엑셀(데이터 › JSON 가져오기)로 열 수 있습니다. 안전한 곳에 보관하세요.

### 3-5. 개인정보 권리 요청 (`/my/account/privacy`)
- 내 개인정보의 **열람 · 정정 · 삭제 · 처리정지**를 요청합니다. 종류를 고르고 내용을 5 ~ 1000자로 적어 「요청 보내기」를 누릅니다. 주민등록번호 · 비밀번호는 적지 마세요.
- 처리 기한은 화면에 표시되며, 결과는 **알림**으로 알려 드립니다. 사정이 있으면 기한을 한 번 늘릴 수 있고 그때 사유를 알려 드립니다.
- 상태: 접수 → (기한 연장) → 처리 완료 또는 거절. 「내 요청」 표에서 확인합니다.
- 바로 할 수 있는 것: 열람은 「내 정보 내려받기」, 이름 · 연락처 정정은 프로필, 모두 지우기는 회원 탈퇴.
- 대리인 요청 등은 고객센터로 문의해 주세요. 법적 기준은 개인정보처리방침(`/terms`)을 보세요.

### 3-6. 알림 (`/my/notifications`)
- 머리줄 종 모양 단추를 누르면 알림 센터가 열리고, 읽지 않은 수가 표시됩니다.
- 거래 · 정산 · 검수 · 계약 · 약관 변경 · 권리 요청 결과 같은 소식이 쌓입니다. 알림을 누르면 관련 화면으로 갑니다.
- 아래 「수신 설정」에서 종류별로 켜고 끌 수 있습니다. 돈 · 계약이 걸린 안내는 끌 수 없습니다.
- **이메일 · 문자 · 알림톡 발송은 준비 중**입니다. 지금은 사이트 안 알림만 나갑니다.

