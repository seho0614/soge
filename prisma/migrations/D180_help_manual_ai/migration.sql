## 8. 고객센터 · 문의 · 약관

### 8-1. 고객센터 (`/support/new`)
- 자주 묻는 질문을 먼저 찾아보고, 답이 없으면 아래 문의 양식으로 보내세요. 영업일 기준 1일 이내 답변이 목표입니다.
