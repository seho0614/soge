CREATE TABLE IF NOT EXISTS public.help_docs (
  id          bigserial PRIMARY KEY,
  code        text NOT NULL CHECK (code ~ '^[A-Z][A-Z_]{2,29}$'),
  version     int  NOT NULL CHECK (version > 0),
  title       text NOT NULL CHECK (char_length(title) BETWEEN 2 AND 80),
  body        text NOT NULL CHECK (char_length(body) BETWEEN 100 AND 20000),
  note        text CHECK (note IS NULL OR char_length(note) <= 200),
  created_by  uuid,
  created_at  timestamptz NOT NULL DEFAULT now(),
  UNIQUE (code, version)
);
COMMENT ON TABLE public.help_docs IS
  '설명서 판(v10.203 · D180 · docs/324) — 고치면 새 판을 더하고 옛 판은 남김(고치기 · 지우기 막음). USER_MANUAL = 회원용 사용자 설명서 · AI 상담 참고 자료 · 사용자 웹 /guide/manual.';

CREATE OR REPLACE FUNCTION public.fn_help_docs_guard() RETURNS trigger
    LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'HELP_DOC_LOCKED: 설명서 판은 고치거나 지울 수 없습니다 — 새 판으로 저장하십시오.' USING ERRCODE = 'P0001';
END $$;
DROP TRIGGER IF EXISTS trg_help_docs_guard ON public.help_docs;
CREATE TRIGGER trg_help_docs_guard BEFORE UPDATE OR DELETE ON public.help_docs
    FOR EACH ROW EXECUTE FUNCTION public.fn_help_docs_guard();

CREATE OR REPLACE VIEW public.v_help_doc_current AS
SELECT DISTINCT ON (code) code, version, title, body, char_length(body) AS chars, note, created_by, created_at
  FROM public.help_docs
 ORDER BY code, version DESC;
COMMENT ON VIEW public.v_help_doc_current IS '설명서 종류마다 가장 높은 판(D180)';

INSERT INTO public.help_docs (code, version, title, body, note)
