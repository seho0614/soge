## 9. 자주 묻는 질문

**Q1. 개인도 가입하고 소개비를 받을 수 있나요?**
네. 개인 회원도 가입할 수 있고, 본인인증을 하면 모든 업무와 소개비 받기가 됩니다. 사업자 인증은 세금계산서로 받을 때만 필요합니다.

**Q2. 소개비는 얼마인가요?**
정해진 요율표가 없습니다. 당사자끼리 협의해 정하고, 소개뱅크는 한 푼도 떼지 않습니다.

**Q3. 소개비는 누가, 어떻게 주나요?**
거래 당사자가 소개자에게 직접 지급합니다. 소개뱅크는 대신 받거나 보내지 않습니다. 「나의공간 › 정산 · 지급」에서 진행 상태를 봅니다.

**Q4. 소개뱅크는 무엇으로 돈을 버나요?**
구독료와 추가 소개코드 발급비, 광고입니다. 거래금액에 따른 수수료는 없습니다.

**Q5. 등록한 매물이 안 보여요.**
검수 승인 전에는 노출되지 않습니다. 「나의공간 › 내 등록 리스팅」에서 상태를 확인하고, 오래 걸리면 고객센터 1:1 문의로 알려 주세요.

**Q6. 소개코드로 들어왔는데 다른 사람이 소개자로 잡혔어요.**
처음 들어온 소개코드가 90일 동안 유지됩니다. 그 뒤에 다른 코드로 들어와도 바뀌지 않습니다.

**Q7. 무료 회원도 소개코드를 받나요?**
무료(베이직) 요금제에는 무료 소개코드가 없고 건마다 추가 결제 뒤 받습니다. 결제 연동은 준비 중입니다.

**Q8. 소개몰에서 주문이 안 돼요.**
지금은 결제 연동 준비로 주문을 받지 않습니다. 상품 보기와 장바구니 담기는 됩니다.

**Q9. 비밀번호 재설정 메일이 안 와요.**
스팸함을 확인하세요. 메일 발송 준비 중이라는 안내가 나오면 고객센터 「계정」 문의로 알려 주세요.

**Q10. 로그인이 잠겼어요.**
비밀번호를 5번 틀리면 30분 동안 잠깁니다. 30분 뒤 다시 시도하거나 「비밀번호 찾기」를 이용하세요.

**Q11. 다른 사람이 내 계정에 들어온 것 같아요.**
「나의공간 › 프로필 · 사업자 정보 › 로그인 기록 · 보안」에서 기록을 보고, 비밀번호를 바꾼 뒤 「모든 기기에서 로그아웃」을 누르세요.

**Q12. 내 정보를 받아 보거나 지우고 싶어요.**
받기는 「내 정보 내려받기」(`/my/account/data`), 정정 · 삭제 · 처리정지는 「개인정보 권리 요청」(`/my/account/privacy`), 모두 지우기는 회원 탈퇴입니다.

**Q13. 탈퇴가 안 돼요.**
진행 중인 거래 · 정산 · 주문이 있으면 끝난 뒤 탈퇴할 수 있습니다. 탈퇴 화면의 「남은 일」을 확인하세요.

**Q14. 로그인 없이 투표할 수 있나요?**
네. 비로그인은 기기 1표, 회원은 1인 1표입니다. 넣은 표는 바꿀 수 없습니다.

**Q15. 첫 글이 바로 안 올라가요.**
첫 글은 확인 후 올라갑니다(보통 하루 안). 두 번째 글부터는 바로 올라갑니다.

**Q16. 신고하면 바로 내려가나요?**
아니요. 운영이 확인한 뒤 처리하고, 결과를 신고한 분께 알려 드립니다.

**Q17. 이메일이나 문자 알림이 오지 않아요.**
이메일 · 문자 · 알림톡 발송은 준비 중입니다. 지금은 사이트 안 알림(종 모양 단추)으로만 알려 드립니다.

**Q18. 본인인증이 안 돼요.**
휴대폰 본인확인 연동은 준비 중입니다. 진행이 막히면 고객센터로 문의해 주세요.

**Q19. 부동산도 올릴 수 있나요?**
공인중개사 인증 등 필요한 인증을 받은 뒤 안심소개에 올릴 수 있습니다. 소개뱅크는 중개보수를 받지 않습니다.

