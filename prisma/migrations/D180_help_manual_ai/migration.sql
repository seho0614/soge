## 5. 안심소개 · 소개몰

### 5-1. 안심소개 상담 신청 (`/mal/consult`)
- 이사 · 청소 · 인테리어 · 렌탈 · 보험 같은 생활 · 금융 상담을 신청하면 **인증업체 1곳**이 연락합니다. 신청 정보는 그 1곳에만 전달됩니다.
- 로그인하지 않아도 신청할 수 있습니다. 이름 · 휴대폰 · 이메일 · 지역을 적고, 휴대폰 확인(인증번호 6자리)을 마쳐야 업체에 전달됩니다.
- 같은 번호로 하루에 신청할 수 있는 횟수가 정해져 있고, 같은 업종은 24시간 안에 다시 신청할 수 없습니다. 업체가 정해진 시간 안에 확인하지 않으면 다른 1곳으로 넘어갑니다.
- 자격 확인 업종(보험 · 의료 등)은 자격 심사를 통과한 업체에만 연결합니다. 법률 · 세무는 사무소 정보를 보고 직접 연락하는 방식입니다.
- 로그인한 채 신청하면 「내 상담 신청」에서 연락처를 받아 간 업체를 볼 수 있습니다.
- **인증번호 발송(문자 · 메일)이 준비 중**이라 신청이 닫혀 있거나 "아직 받지 않습니다"가 보일 수 있습니다. 그때는 고객센터로 문의해 주세요.
- 소개뱅크는 자격을 확인할 뿐 상담 결과를 보증하지 않습니다.

### 5-2. 소개몰 둘러보기 (`/health`)
- 건강식품 등 건강 상품을 소개뱅크가 직접 파는 쇼핑몰입니다. 고민별 · 성분별 찾기, 상품 검색이 있습니다.
- 의약품 · 의료 서비스는 팔지 않습니다.

### 5-3. 소개몰 주문 — 지금은 받지 않습니다
- **지금은 소개몰 주문을 받지 않습니다.** 결제 연동을 준비 중이기 때문입니다.
- 상품 보기와 장바구니(`/health/cart`) 담기는 됩니다. 주문 단추 대신 안내가 보입니다.
- 주문이 열리면 사이트에서 알려 드립니다. 그 전에 결제를 요구하는 연락은 응하지 마세요.

### 5-4. 주문 조회 · 취소 · 반품 · 환불 (주문이 열린 뒤)
- 주문 · 배송 조회: 「나의공간 › 소개몰 주문」(`/my/health/orders`).
- 취소 · 반품 신청: `/my/health/returns/new`, 처리 결과: `/my/health/returns`. 배송지 관리: `/my/health/addresses`.
- 발송 전 취소와 판매자 사유(파손 · 오배송 · 표시와 다름 · 지연)는 전액 환불됩니다. 회원 사정(단순 변심 등) 반품은 왕복 배송비를 빼고 환불하며, 금액은 신청 화면에 표시됩니다.
- 자세한 기준은 약관 화면(`/terms`)의 판매 · 환불 약관을 따릅니다.

