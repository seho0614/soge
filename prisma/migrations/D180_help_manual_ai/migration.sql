## 6. 소개광장

### 6-1. 글 쓰기 (`/community`)
- 게시판: 소개 후기 · 업종 이야기 · 질문 · 공지 · 우리동네 맛집 · 「이건 어때?」 투표.
- 로그인하면 누구나 글을 쓸 수 있습니다(`/community/write`). 제목과 내용을 쓰면 게시판을 골라 드리며, 맞지 않으면 직접 고르세요. 제목 2 ~ 100자, 내용 10자 이상입니다.
- **첫 글은 확인 후 올라갑니다**(보통 하루 안). 두 번째부터는 바로 올라갑니다.
- 가입 7일이 안 되면 링크를 넣을 수 없고, 하루에 쓸 수 있는 글 수가 정해져 있습니다.
- 소개 후기는 성사된 거래가 있어야 쓸 수 있습니다.
- 우리동네 맛집(`/community/food`)은 카카오맵에서 가게를 찾아 고릅니다. 대가를 받고 쓴 글은 반드시 「광고 · 협찬」에 체크하세요.
- 동네 인증(위치 확인)은 준비 중입니다.

### 6-2. 댓글
- 로그인하면 댓글을 달 수 있습니다(두 글자 이상). 답글은 1단계까지입니다.
- "신고가 들어와 가려진 댓글" 또는 "운영 기준에 따라 가려진 댓글"로 보이는 것은 운영 확인 중이거나 운영이 감춘 댓글입니다.

### 6-3. 신고
- 글 · 댓글 · 매물 등의 「신고」 단추를 누르고 문제점을 적습니다(`/report/...`).
- 신고 1건으로 바로 내려가지 않습니다. 여러 사람이 짜고 남의 글을 내리는 일을 막기 위해서입니다. 신고가 여러 건 쌓이면 운영 확인 때까지 가려질 수 있습니다.
- 처리 결과는 신고한 분께 알려 드립니다. 내 신고는 「나의공간 › 내 신고 내역」(`/my/reports`)에서 봅니다.

### 6-4. 「이건 어때?」 투표 (`/community/polls`)
- **로그인 없이도 투표할 수 있습니다.** 회원은 1인 1표, 비로그인은 기기 1표입니다.
- 같은 인터넷 주소에서는 투표 1건당 하루에 넣을 수 있는 표 수가 정해져 있습니다(운영이 정함).
- 넣은 표는 바꿀 수 없고, 결과는 투표한 뒤에 보입니다. 참여 수는 실제로 투표한 수입니다.
- 회원 투표 만들기(`/community/polls/new`)는 운영이 열었을 때만 쓸 수 있습니다. 만들자마자 열리고, 링크 · 금칙어는 넣을 수 없으며, 표가 들어온 뒤에는 고치거나 지울 수 없고 마감만 됩니다. 신고 3건이면 운영 확인 때까지 감춰집니다. 가입 직후에는 만들 수 없고 하루 만들 수 있는 수가 정해져 있습니다. 내 투표는 `/community/polls/mine`.

