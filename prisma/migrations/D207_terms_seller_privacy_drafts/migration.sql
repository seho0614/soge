## 제13조 (변경)
이 방침이 바뀌면 **시행 7일 전**에 알려 드립니다.

- 1.1 (〔시행일〕) — 추천 관계 · 추천 보상 기록 · 포인트 출금 주민등록번호 수집 · 보관 기간 추가

---

시행일 〔시행일〕$D207P$;
  v_d155   text := '7fd91050ff95721e7af3fff90d6bb55f';
  r record; v_ver text; n int;
BEGIN
  /* ① 입점 약관 1.0 초안 */
  SELECT * INTO r FROM public.terms WHERE code = 'HLT_SELLER' AND version = '1.0';
  IF r.code IS NULL THEN
    RAISE NOTICE 'D207 HLT_SELLER 1.0 없음 — 건너뜀';
  ELSIF r.status NOT IN ('DRAFT', 'LEGAL_REVIEW') THEN
    RAISE NOTICE 'D207 HLT_SELLER 1.0 은 % — 손대지 않음', r.status;
  ELSIF r.body = v_seller THEN
    NULL;
  ELSIF md5(r.body) <> v_d155 THEN
    RAISE NOTICE 'D207 HLT_SELLER 1.0 초안을 이미 고쳤음 — 덮어쓰지 않음(docs/400 을 보고 손으로 맞추십시오)';
  ELSE
    UPDATE public.terms SET body = v_seller,
           change_note = 'v10.273 (D207) 입점 약관 1.0 게시용 완성본(docs/400 · 법무 · 세무 확인 11/13) — 남은 빈칸: 수수료율 2칸 · 시행일'
     WHERE code = 'HLT_SELLER' AND version = '1.0' AND status IN ('DRAFT', 'LEGAL_REVIEW');
    RAISE NOTICE 'D207 HLT_SELLER 1.0 초안 본문을 docs/400 으로 바꿈';
  END IF;

  /* ② 처리방침 1.1 초안 */
  IF EXISTS (SELECT 1 FROM public.terms WHERE code = 'PRIVACY' AND body = v_priv) THEN
    RETURN;
  END IF;
  SELECT count(*) INTO n FROM public.terms WHERE code = 'PRIVACY' AND status IN ('DRAFT', 'LEGAL_REVIEW');
  IF n > 0 THEN
    RAISE NOTICE 'D207 PRIVACY 초안이 이미 % 개 — 새 초안을 넣지 않음(docs/401 을 보고 손으로 맞추십시오)', n;
    RETURN;
  END IF;
  SELECT * INTO r FROM public.terms WHERE code = 'PRIVACY' AND status = 'PUBLISHED'
   ORDER BY split_part(version, '.', 1)::int DESC, split_part(version, '.', 2)::int DESC LIMIT 1;
  IF r.code IS NULL THEN
    RAISE NOTICE 'D207 게시된 PRIVACY 없음 — 건너뜀';
    RETURN;
  END IF;
  v_ver := split_part(r.version, '.', 1) || '.' || (split_part(r.version, '.', 2)::int + 1);
  WHILE EXISTS (SELECT 1 FROM public.terms WHERE code = r.code AND version = v_ver) LOOP
    v_ver := split_part(v_ver, '.', 1) || '.' || (split_part(v_ver, '.', 2)::int + 1);
  END LOOP;
  INSERT INTO public.terms (code, version, title, body, is_required, effective_from, status, display_order, gwan_code, change_note, is_notice)
  VALUES (r.code, v_ver, r.title, v_priv, r.is_required, 'infinity', 'DRAFT', r.display_order, r.gwan_code,
          'v10.273 (D207) 처리방침 1.1 게시용 완성본(docs/401 · 법무 확인 11/13) — 추천 관계 · 추천 보상 · 포인트 출금 주민등록번호 · 보관 기간. 남은 빈칸: 법령 근거 2칸 · 시행일', r.is_notice);
  RAISE NOTICE 'D207 PRIVACY % 초안(DRAFT) — 게시된 % 는 그대로', v_ver, r.version;
END $$;
