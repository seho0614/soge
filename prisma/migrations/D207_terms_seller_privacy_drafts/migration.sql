## 제1장 총칙

### 제1조 (목적)

이 약관은 (주)한국바이오헬스케어 소개뱅크 사업부(이하 "회사")가 운영하는 소개몰에 입점하여 상품을 판매하는 판매자와 회사 사이의 권리, 의무, 책임과 이용 조건을 정합니다.

### 제2조 (정의)

1. **소개몰**: 회사가 소개뱅크 안에서 운영하는 상품 판매 서비스.
2. **판매자**: 이 약관에 동의하고 회사의 입점 승인을 받아 소개몰에서 상품을 판매하는 회원(개인 또는 사업자).
3. **브랜드 직영관**: 제조사 또는 브랜드 권리자가 자기 상품을 직접 판매하는 입점 유형.
4. **일반 입점**: 브랜드 직영관이 아닌 판매자의 입점 유형.
5. **구매자**: 소개몰에서 판매자의 상품을 구매하는 회원.
6. **검수**: 판매자가 등록한 상품을 노출하기 전에 회사가 확인하는 절차.
7. **구매확정**: 구매자가 상품 수령 후 구매를 확정하거나, 배송 완료 후 7일이 지나 자동으로 확정된 상태.
8. **판매수수료**: 회사가 제공하는 중개 서비스의 대가로 판매자가 회사에 내는 금액.

### 제3조 (약관의 게시와 개정)

1. 회사는 이 약관을 판매자센터에 게시합니다.
2. 회사는 관계 법령을 위반하지 않는 범위에서 이 약관을 개정할 수 있습니다.
3. 개정할 때에는 시행일과 개정 사유를 밝혀 시행일 7일 전부터 공지합니다. 판매자에게 불리한 개정은 시행일 30일 전부터 공지하고 등록된 연락처로 개별 통지합니다.
4. 판매자가 시행일까지 거부 의사를 밝히지 않으면 동의한 것으로 봅니다. 이 규정은 회사가 공지할 때 그 뜻을 분명히 알린 경우에만 적용합니다.
5. 개정에 동의하지 않는 판매자는 제27조에 따라 이용계약을 해지할 수 있습니다.
6. 이전 판은 판매자가 열람할 수 있도록 보관합니다.

### 제4조 (다른 약관과의 관계)

1. 판매자는 소개뱅크 회원이어야 하며, 이용약관과 개인정보처리방침이 함께 적용됩니다.
2. 입점 판매에 관하여 이 약관과 이용약관이 다르면 이 약관이 우선합니다.
3. 회사가 판매자센터에 공지한 운영 정책(수수료 정책, 검수 기준, 품목 개방 단계)은 이 약관의 일부를 이룹니다.

### 제5조 (회사의 지위)

1. 회사는 입점 판매에서 통신판매중개자이며, 판매자와 구매자 사이 거래의 당사자가 아닙니다.
2. 상품, 거래 정보, 거래에 관한 책임은 판매자에게 있습니다.
3. 회사는 상품 화면과 화면 하단에 제1항의 사실을 고지하며, 판매자는 그 고지 문구의 표시에 동의합니다.
4. 회사가 직접 판매하는 직판 상품에는 이 약관을 적용하지 않습니다.

## 제2장 입점

### 제6조 (입점 자격)

1. 개인 회원과 사업자 회원 모두 판매자가 될 수 있습니다. 회사는 「사업자만」 같은 일반 제한을 두지 않습니다.
2. 관계 법령상 사업자등록, 통신판매업 신고, 영업신고, 등록, 허가가 필요한 판매자와 품목은 그 자격을 갖춘 경우에만 판매할 수 있습니다.
   개인 판매자도 관계 법령이 정한 신고 면제 기준을 넘으면 통신판매업 신고를 해야 하며, 회사는 그 확인 자료를 요청할 수 있습니다.
3. 판매자는 본인확인을 마친 소개뱅크 회원이어야 합니다.

### 제7조 (입점 신청과 심사)

1. 입점하려는 자는 이 약관에 동의하고 아래 서류를 제출하여 신청합니다.

| 서류 | 대상 |
| --- | --- |
| 사업자등록증 | 사업자 판매자 |
| 통신판매업 신고증 | 신고 대상 판매자(면제 대상은 면제 사유) |
| 건강기능식품 영업신고증 | 건강기능식품을 판매하는 판매자 |
| 의료기기 판매업 신고증 | 의료기기를 판매하는 판매자 |
| 화장품책임판매업 등록필증 | 화장품을 제조 또는 수입하여 판매하는 판매자 |
| 브랜드 권리 증빙 | 브랜드 직영관으로 신청하는 판매자 |

2. 이용계약은 회사가 서류를 심사하여 승인한 때에 성립합니다.
3. 회사는 다음의 경우 승인을 보류하거나 거절할 수 있으며, 그 사유를 신청자에게 알립니다.
   1. 제출 서류가 사실과 다르거나 유효기간이 지난 경우
   2. 사업자 상태가 휴업 또는 폐업인 경우
   3. 이 약관에 따라 이용계약이 해지된 이력이 있는 경우
   4. 판매하려는 품목이 제8조의 개방 단계에 해당하지 않는 경우
   5. 그 밖에 구매자 보호에 현저한 지장이 우려되는 경우
4. 판매자는 배송비, 무료배송 조건, 반품지 주소, 고객 응대 연락처를 판매자센터에 등록해야 합니다. 이 정보가 비어 있으면 상품이 노출되지 않습니다.

### 제8조 (품목별 자격과 개방 단계)

1. 판매자가 판매할 수 있는 품목은 승인받은 자격에 따라 정해집니다.
2. 회사는 품목을 단계별로 개방하며, 개방하지 않은 품목은 등록할 수 없습니다.
3. 개방 단계와 품목별 필요 자격은 판매자센터에 공지합니다.

### 제9조 (자격의 유지와 만료)

1. 판매자는 제출한 자격을 계약 기간 동안 유효하게 유지해야 합니다.
2. 회사는 자격 만료 30일 전에 판매자에게 알립니다.
3. 자격이 만료되면 그 자격이 필요한 상품의 노출을 만료일에 중단합니다. 갱신한 자격을 제출하여 승인받으면 노출을 재개합니다.
4. 상호, 대표자, 사업장 주소, 정산 계좌, 자격 내용이 바뀌면 판매자는 지체 없이 수정해야 합니다. 정산 계좌를 바꿀 때에는 본인확인과 계좌 검증을 다시 거칩니다.
5. 회사는 사업자 상태와 자격의 유효 여부를 주기적으로 다시 확인할 수 있습니다.

## 제3장 상품 등록과 판매

### 제10조 (상품 등록과 검수)

1. 판매자는 판매자센터의 양식에 따라 상품을 등록합니다.
2. 등록한 상품은 검수를 통과한 뒤에 노출됩니다.
3. 회사는 자동 사전검사와 담당자 확인으로 검수하며, 다음에 해당하면 등록을 반려하고 사유를 알립니다.
   1. 법령상 필수 표시사항(상품정보제공고시)이 빠진 경우
   2. 섭취 또는 사용상 주의사항이 필요한 품목인데 적지 않은 경우
   3. 질병의 예방, 치료, 완치를 단정하는 등 금지된 표현이 있는 경우
   4. 광고 심의가 필요한 품목인데 심의필이 없거나 심의받은 문구와 다른 경우
   5. 품목에 필요한 자격을 갖추지 못한 경우
4. 검수 통과는 회사가 상품의 적법성이나 품질을 보증한다는 뜻이 아닙니다.
5. 판매자가 광고 문구를 수정하면 다시 검수를 받습니다. 재검수 중에는 직전에 승인된 문구로 표시됩니다.
6. 판매자는 반려에 이의를 신청할 수 있고, 회사는 처리 결과를 회신합니다.

### 제11조 (표시와 광고)

1. 상품의 표시와 광고에 관한 책임은 판매자에게 있습니다.
2. 판매자는 식품, 건강기능식품, 화장품, 의료기기에 관한 표시·광고 법령과 심의 기준을 지켜야 합니다.
3. 판매자는 광고 내용이 사실임을 입증할 자료를 보관하고, 회사나 관계 기관이 요청하면 제출합니다.
4. 회사는 법령 위반이 의심되는 표시·광고의 노출을 먼저 중단하고 판매자에게 소명을 요청할 수 있습니다.

### 제12조 (판매할 수 없는 상품)

판매자는 다음 상품을 등록하거나 판매할 수 없습니다.

1. 법령상 판매가 금지되거나 통신판매가 금지된 상품
2. 자격 없이 판매할 수 없는 품목으로서 판매자가 그 자격을 갖추지 못한 상품
3. 타인의 상표권, 저작권 등 권리를 침해하는 상품
4. 유통기한 또는 사용기한이 지났거나 임박하여 구매자가 정상적으로 사용할 수 없는 상품
5. 회수, 판매 중지 명령을 받은 상품
6. 회사가 판매자센터에 공지한 취급 제한 상품

### 제13조 (가격, 재고, 판매 조건)

1. 판매 가격과 재고는 판매자가 정하고 관리합니다.
2. 판매자는 등록한 가격과 조건대로 판매해야 하며, 주문이 접수된 뒤에 가격이나 조건을 구매자에게 불리하게 바꿀 수 없습니다.
3. 재고가 없는데 주문이 접수된 경우, 판매자는 지체 없이 구매자에게 알리고 주문을 취소합니다. 이때 드는 비용은 판매자가 부담합니다.
4. 정가를 허위로 높여 할인율을 부풀리는 표시는 금지합니다.
5. 쿠폰과 할인 행사의 비용 부담 주체는 행사마다 회사와 판매자가 사전에 정합니다. 정하지 않은 행사 비용을 회사가 판매자에게 부담시키지 않습니다.

## 제4장 주문·배송·반품

### 제14조 (주문과 배송)

1. 판매자는 결제가 완료된 주문을 확인하고, 결제일부터 3영업일 이내에 발송에 필요한 조치를 합니다.
2. 판매자는 발송 후 택배사와 송장번호를 판매자센터에 등록합니다.
3. 기한 안에 발송할 수 없으면 판매자는 지체 없이 그 사유와 예정일을 구매자에게 알립니다.
4. 배송 중 분실, 파손에 대한 책임은 판매자에게 있습니다.
5. 여러 판매자의 상품을 함께 주문하면 주문은 판매자별로 나뉘고 배송비도 판매자별로 붙습니다.

### 제15조 (취소, 반품, 환불)

1. 발송 전 주문은 구매자가 요청하면 판매자의 승인 없이 즉시 취소됩니다.
2. 구매자는 상품을 받은 날부터 7일 이내에 청약을 철회할 수 있습니다.
3. 상품이 표시·광고 내용과 다르거나 계약과 다르게 이행된 경우, 구매자는 상품을 받은 날부터 3개월 이내, 그 사실을 안 날 또는 알 수 있었던 날부터 30일 이내에 철회할 수 있습니다.
4. 반품 배송비는 다음과 같이 부담합니다.

| 사유 | 부담 | 금액 |
| --- | --- | --- |
| 구매자 사정(단순 변심, 잘못 주문) | 구매자 | 판매자가 판매자센터에 정한 왕복 배송비(6,000원을 넘을 수 없음)를 환불 금액에서 뺍니다. 금액은 상품 화면에 표시합니다 |
| 판매자 사유(파손, 오배송, 표시와 다름, 배송 지연) | 판매자 | 구매자 부담 없음 |

5. 판매자는 구매자 사정의 반품에 대해 제4항의 배송비 외에 위약금이나 손해배상을 청구할 수 없습니다.
6. 판매자는 반품 상품을 받은 날부터 3영업일 이내에 환불에 필요한 조치를 합니다.
7. 법령상 청약철회가 제한되는 상품은 판매자가 그 사실을 상품 화면에 구매자가 쉽게 알 수 있도록 표시한 경우에만 제한을 주장할 수 있습니다.
8. 판매자는 이 조보다 구매자에게 불리한 반품 조건을 정할 수 없습니다.

### 제16조 (고객 응대와 분쟁 중재)

1. 판매자는 구매자의 문의에 2영업일 이내에 답변합니다.
2. 판매자가 반품이나 환불을 거부하고 구매자가 이의를 제기하면 회사가 중재합니다. 중재가 진행되는 동안 판매자는 해당 건을 처리할 수 없습니다.
3. 회사는 양쪽의 주장과 증빙을 확인하여 판정하고, 판정에 따라 환불을 실행하며 정산을 조정합니다.
4. 회사의 판정은 판매자와 구매자가 법령에 따라 가지는 권리의 행사를 막지 않습니다.
5. 상품 후기는 구매자만 작성할 수 있습니다. 판매자는 대가를 주고 후기를 쓰게 하거나 후기를 조작할 수 없습니다.

## 제5장 수수료와 정산

### 제17조 (판매수수료)

1. 판매자는 구매확정된 판매 금액에 요율을 곱한 판매수수료를 회사에 냅니다.
2. 요율은 다음과 같습니다.

| 입점 유형 | 요율 |
| --- | --- |
| 브랜드 직영관 | 〔 〕% |
| 일반 입점 | 〔 〕% |

3. 품목별로 요율이 다르면 회사는 그 표를 판매자센터에 공지합니다.
4. 회사가 요율을 올릴 때에는 시행일 30일 전에 공지하고 개별 통지하며, 시행일 이후 접수된 주문부터 적용합니다.
5. 회사는 판매수수료, 결제대행 수수료, 제13조 제5항에 따라 정한 행사 비용 외의 금액을 판매자에게 부과하지 않습니다.

### 제18조 (판매대금의 수취)

1. 구매자가 결제한 판매대금은 결제대행사를 통해 판매자의 하위가맹점 계정으로 귀속됩니다.
2. 회사는 판매대금을 보관하지 않으며, 판매수수료만 받습니다.
3. 판매자는 입점 승인 후 결제대행사의 하위가맹점 등록을 마쳐야 판매를 시작할 수 있습니다.

### 제19조 (정산)

1. 정산 대상은 구매확정된 주문입니다.
2. 정산액은 다음과 같이 계산합니다.

| 구분 | 항목 |
| --- | --- |
| 더하는 것 | 구매확정된 상품 금액, 판매자에게 귀속되는 배송비 |
| 빼는 것 | 판매수수료, 결제대행 수수료, 판매자가 부담하기로 한 쿠폰 할인액 |
| 조정 | 제20조의 환불 조정액 |

3. 정산은 주 1회 마감하며, 지급은 결제대행사가 그 지급 주기에 따라 판매자에게 합니다. 회사는 마감한 정산액을 결제대행사에 지급 요청합니다.
4. 회사는 주문 단위의 정산 명세를 판매자센터에서 제공합니다.
5. 판매자는 정산 명세에 이의가 있으면 명세를 받은 날부터 30일 이내에 신청합니다.
6. 회사는 다음의 경우 해당 금액의 지급을 보류할 수 있고, 그 사유를 판매자에게 알립니다.
   1. 정산 계좌의 검증이 끝나지 않은 경우
   2. 제16조의 중재가 진행 중인 주문
   3. 법원의 압류 등 법령에 따른 지급 제한이 있는 경우

### 제20조 (환불에 따른 정산 조정)

1. 정산이 끝난 주문이 환불되면 그 금액을 다음 회차 정산에서 뺍니다.
2. 환불된 주문의 판매수수료는 회사가 전액 되돌려 줍니다.
3. 결제대행 수수료의 환급 여부는 결제대행사의 정책에 따릅니다.
4. 조정 후 정산액이 0원보다 작으면 지급을 보류하고 다음 회차로 넘깁니다.
5. 같은 주문 상품은 한 번만 정산합니다.

### 제21조 (세금계산서와 증빙)

1. 회사는 판매수수료에 대하여 판매자에게 세금계산서를 발행합니다.
2. 구매자에 대한 현금영수증 등 거래 증빙은 거래 당사자인 판매자가 발행합니다.
3. 발행에 필요한 정보는 판매자가 정확히 등록해야 합니다.

## 제6장 개인정보와 책임

### 제22조 (구매자 개인정보)

1. 회사는 구매자의 동의를 받아 배송에 필요한 정보(받는 사람, 연락처, 주소, 주문 내용)를 판매자에게 제공합니다.
2. 판매자는 제공받은 정보를 배송, 반품, 고객 응대 목적으로만 사용합니다.
3. 판매자는 구매자 정보를 광고, 판촉, 다른 서비스 가입 권유에 쓰거나 제3자에게 넘길 수 없습니다. 배송 업무를 맡은 택배사에 전달하는 것은 예외입니다.
4. 판매자는 목적을 달성한 정보를 지체 없이 파기합니다. 법령상 보존 의무가 있는 거래 기록은 그 기간 동안 보관합니다.
5. 판매자는 구매자 정보가 유출된 사실을 알면 즉시 회사에 알리고 필요한 조치를 합니다.
6. 회사는 판매자센터에서 구매자 연락처를 일부 가려서 표시할 수 있고, 전체 열람 기록을 남길 수 있습니다.

### 제23조 (지식재산과 상품 정보의 이용)

1. 판매자가 등록한 상품 정보와 이미지의 권리는 판매자에게 있습니다.
2. 판매자는 회사가 상품의 노출, 검색, 홍보를 위해 그 정보를 소개뱅크 안팎에서 사용하는 것을 허락합니다. 이 허락은 계약 기간 동안 유효하며, 해지 후에는 회사가 지체 없이 노출을 중단합니다.
3. 판매자는 등록한 정보가 타인의 권리를 침해하지 않음을 보증합니다.
4. 권리 침해 신고가 접수되면 회사는 해당 상품의 노출을 먼저 중단하고 판매자에게 소명을 요청할 수 있습니다.

### 제24조 (손해배상)

1. 판매자가 이 약관이나 법령을 위반하여 회사 또는 구매자에게 손해를 입히면 그 손해를 배상합니다.
2. 상품의 결함, 허위 표시, 권리 침해로 회사가 구매자나 제3자에게 배상하거나 과징금 등을 부담한 경우, 회사는 판매자에게 그 금액을 청구할 수 있습니다.
3. 회사가 고의 또는 과실로 판매자에게 손해를 입히면 회사가 그 손해를 배상합니다.

### 제25조 (회사의 책임 범위)

1. 회사는 거래 당사자가 아니므로 판매자와 구매자 사이의 거래에서 생긴 분쟁에 대해 책임을 지지 않습니다. 회사의 고의 또는 과실이 있는 경우에는 그러하지 않습니다.
2. 회사는 천재지변, 통신 장애 등 회사가 통제할 수 없는 사유로 서비스를 제공하지 못한 경우 책임을 지지 않습니다.
3. 회사는 서비스 점검이 필요하면 미리 공지하고 서비스를 일시 중단할 수 있습니다.
4. 회사는 판매량이나 매출을 보증하지 않습니다.

## 제7장 이용 제한·해지·분쟁

### 제26조 (이용 제한)

1. 회사는 판매자가 다음에 해당하면 경고, 상품 노출 중단, 판매 정지, 계약 해지의 순서로 조치할 수 있습니다.
   1. 허위 서류를 제출하거나 자격 없이 판매한 경우
   2. 제12조의 상품을 등록하거나 판매한 경우
   3. 발송 지연, 미발송, 환불 지연이 반복되는 경우
   4. 구매자 정보를 제22조의 목적 밖으로 사용한 경우
   5. 후기를 조작하거나 소개몰 밖의 결제를 유도한 경우
   6. 그 밖에 이 약관이나 법령을 위반한 경우
2. 회사는 조치 전에 사유를 알리고 소명할 기회를 줍니다. 구매자 피해가 급박하면 먼저 조치하고 지체 없이 알립니다.
3. 위반의 정도가 무거우면 회사는 앞 단계를 거치지 않고 판매 정지 또는 해지를 할 수 있습니다.
4. 판매자는 조치에 이의를 신청할 수 있고, 회사는 영업일 7일 이내에 회신합니다.

### 제27조 (계약의 해지)

1. 판매자는 언제든지 판매자센터에서 해지를 신청할 수 있습니다.
2. 진행 중인 주문, 반품, 중재, 정산이 남아 있으면 그 절차가 끝난 때에 해지됩니다.
3. 회사는 제26조에 따라 계약을 해지할 수 있습니다.
4. 해지 후에도 판매자는 이미 판매한 상품의 반품, 환불, 하자에 대한 책임을 집니다.
5. 남은 정산금은 판매한 상품의 청약철회 기간이 지난 뒤 제19조에 따라 지급합니다.

### 제28조 (준거법과 관할)

1. 이 약관에는 대한민국 법을 적용합니다.
2. 이 약관에 관한 분쟁은 회사의 주소지를 관할하는 법원을 제1심 관할 법원으로 합니다.

