-- v10.31 (10/10 「시안 기준」 지시 · 운영 화면 W6) — 핵심 서버 자료
--   ① 정산 「승인」 단계(시안 SB-ADM-STL-010 「신청 → 승인 → 지급 실행」)
--      INV-11(자금 수탁 금지)의 보호는 그대로 둡니다:
--        · 승인은 「정산서가 맞다」는 운영 확인일 뿐 돈을 받거나 보내지 않습니다 — 계좌 · 결제 컬럼을 새로 두지 않습니다(v_inv11_violations 0 유지).
--        · 지급은 여전히 당사자(지불 측)가 직접 하고, 지급 표시는 당사자만 찍습니다(trg_settlement_paid_actor 그대로).
--        · 승인자는 운영(ADMIN · SUPER) 계정이어야 하고, 그 거래의 당사자(지불 · 수령 · 소개자)는 승인할 수 없습니다(2인 원칙 — 승인과 지급 분리).
--        · 분쟁 보류 · 받을 계좌 미확인 · 예금주 불일치 건은 승인이 막힙니다.
--        · 승인은 지울 수 없는 기록(settlement_approvals)에 남습니다 — 누가 언제 무엇을 승인했는지.
--   ② 회원 상태 변경(정지 · 정상) 기록 · 사업자 신청 반려 기록
--   ③ 운영 설정: 검수 처리 한계(review.daily_capacity) · 직업정보제공사업 신고번호(footer.job_info_no)

