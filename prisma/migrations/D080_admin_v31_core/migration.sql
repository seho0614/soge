CREATE TABLE IF NOT EXISTS settlement_approvals (
  id            bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  settlement_id uuid NOT NULL REFERENCES settlements(id),
  approved_by   uuid NOT NULL REFERENCES accounts(id),
  approved_at   timestamptz NOT NULL DEFAULT now(),
  amount        numeric(14,0) NOT NULL,
  note          text
);
COMMENT ON TABLE settlement_approvals IS 'v10.31 — 정산 승인 기록(지울 수 없음). 승인은 정산서 확인이며 자금 이동이 아님(INV-11)';
CREATE INDEX IF NOT EXISTS idx_stl_approvals_stl ON settlement_approvals (settlement_id);

CREATE OR REPLACE FUNCTION fn_settlement_approvals_immutable() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'STL_LOG: 정산 승인 기록은 고치거나 지울 수 없습니다';
END $$;
DROP TRIGGER IF EXISTS trg_stl_approvals_immutable ON settlement_approvals;
CREATE TRIGGER trg_stl_approvals_immutable BEFORE UPDATE OR DELETE ON settlement_approvals
  FOR EACH ROW EXECUTE FUNCTION fn_settlement_approvals_immutable();

/* 승인 · 지급 표시 순서와 2인 원칙 */
CREATE OR REPLACE FUNCTION fn_settlement_approval() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE d record; v_bad text;
BEGIN
  IF TG_OP = 'UPDATE' AND NEW.status = 'APPROVED' AND OLD.status IS DISTINCT FROM 'APPROVED' THEN
    IF OLD.status <> 'REQUESTED' THEN
      RAISE EXCEPTION 'STL_APPROVE: 승인 대기(신청) 상태의 정산만 승인할 수 있습니다';
    END IF;
    IF NEW.approved_by IS NULL OR NOT EXISTS (
         SELECT 1 FROM account_roles r WHERE r.account_id = NEW.approved_by AND r.role IN ('ADMIN','SUPER')) THEN
      RAISE EXCEPTION 'STL_APPROVE: 운영(ADMIN · SUPER) 계정만 승인할 수 있습니다';
    END IF;
    SELECT * INTO d FROM deals WHERE id = NEW.deal_id;
    IF NEW.approved_by IN (NEW.payee_account_id, d.seller_account_id, d.buyer_account_id, d.introducer_account_id) THEN
      RAISE EXCEPTION 'STL_APPROVE: 거래 당사자는 자기 정산을 승인할 수 없습니다(2인 원칙)';
    END IF;
    IF NEW.held_by_dispute_id IS NOT NULL OR EXISTS (
         SELECT 1 FROM disputes x WHERE x.deal_id = NEW.deal_id AND x.status IN ('OPEN','IN_REVIEW')) THEN
      RAISE EXCEPTION 'STL_APPROVE: 분쟁이 걸린 거래의 정산은 승인할 수 없습니다';
    END IF;
    IF NEW.payee_business_id IS NULL THEN
      SELECT CASE
               WHEN p.id IS NULL THEN '받을 계좌 확인이 끝나지 않았습니다'
               WHEN NOT p.verified THEN '받을 계좌 1원 확인이 끝나지 않았습니다'
               WHEN regexp_replace(p.holder_name, '\s', '', 'g') <> regexp_replace(a.name, '\s', '', 'g')
                 THEN '예금주명이 회원 이름과 다릅니다 — 수동 검증 대기'
             END INTO v_bad
        FROM accounts a
        LEFT JOIN LATERAL (SELECT * FROM payout_accounts q WHERE q.account_id = a.id
                            ORDER BY q.is_default DESC, q.verified DESC, q.created_at DESC LIMIT 1) p ON true
       WHERE a.id = NEW.payee_account_id;
      IF v_bad IS NOT NULL THEN RAISE EXCEPTION 'STL_APPROVE: %', v_bad; END IF;
    END IF;
    NEW.approved_at := now();
  END IF;

  /* 지급 표시(당사자)는 운영 승인 뒤에만 */
  IF TG_OP = 'UPDATE' AND NEW.status = 'PAID' AND OLD.status IS DISTINCT FROM 'PAID' AND OLD.status <> 'APPROVED' THEN
    RAISE EXCEPTION 'STL_PAID: 운영 승인 전에는 지급 표시를 할 수 없습니다';
  END IF;

  /* 보류 · 반려 · 다시 신청으로 돌아가면 승인은 풀립니다(기록은 settlement_approvals 에 남음) */
  IF TG_OP = 'UPDATE' AND NEW.status IN ('REQUESTED','HELD','REJECTED') AND OLD.status = 'APPROVED' THEN
    NEW.approved_by := NULL; NEW.approved_at := NULL;
  END IF;
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS trg_settlement_approval ON settlements;
CREATE TRIGGER trg_settlement_approval BEFORE UPDATE ON settlements
  FOR EACH ROW EXECUTE FUNCTION fn_settlement_approval();

/* 승인 기록은 승인되는 순간 같은 거래에서 남깁니다 */
CREATE OR REPLACE FUNCTION fn_settlement_approval_log() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.status = 'APPROVED' AND OLD.status IS DISTINCT FROM 'APPROVED' THEN
    INSERT INTO settlement_approvals (settlement_id, approved_by, approved_at, amount)
    VALUES (NEW.id, NEW.approved_by, NEW.approved_at, NEW.amount);
  END IF;
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS trg_settlement_approval_log ON settlements;
CREATE TRIGGER trg_settlement_approval_log AFTER UPDATE ON settlements
  FOR EACH ROW EXECUTE FUNCTION fn_settlement_approval_log();

/* 분쟁이 접수되면 승인된(아직 지급 표시 전) 정산도 보류합니다 */
CREATE OR REPLACE FUNCTION public.fn_hold_settlement_on_dispute() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  UPDATE settlements
     SET status = 'HELD', held_by_dispute_id = NEW.id
   WHERE deal_id = NEW.deal_id
     AND status IN ('REQUESTED','APPROVED');
  RETURN NEW;
END $$;

