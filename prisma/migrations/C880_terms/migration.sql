# 구독 환불 정책

## 제1조 (적용 범위)
이 정책은 **소개뱅크 구독료**에 적용됩니다. 회원 사이의 거래
대금이나 소개비는 여기에 해당하지 않습니다.

## 제2조 (청약철회)
① 결제일부터 **7일 안**이면 이유를 묻지 않고 환불해 드립니다
   (전자상거래법 17조).
② 다만 그 사이에 **서비스를 쓰신 경우**에는 쓰신 만큼을 뺀 금액을
   돌려 드립니다.

### 쓰신 것으로 보는 경우
```
소개코드를 발급받은 경우
등록물을 게시한 경우
리드를 열람한 경우
```

## 제3조 (7일이 지난 뒤)
① 남은 기간을 **일할로 계산**해 환불합니다.
② 계산식

```
환불액 = 결제액 × (남은 일수 ÷ 전체 일수) − 이미 쓰신 분
```

③ 월 구독은 다음 결제일까지, 연 구독은 남은 개월 수로 셉니다.

## 제4조 (환불하지 않는 경우)
```
이용 제한·해지된 회원이 그 사유로 해지된 경우
무료로 받으신 기간
프로모션으로 받으신 할인분
```

## 제5조 (처리 기간)
① 신청하신 날부터 **영업일 3일 안**에 처리합니다.
② 카드 결제는 카드사 사정으로 **최대 7영업일**이 더 걸릴 수
   있습니다.

## 제6조 (신청 방법)
```
마이페이지 → 구독 → 환불 신청
또는 1:1 문의
```

## 제7조 (구독 해지)
① 언제든지 해지하실 수 있습니다.
② 해지하셔도 **이미 결제한 기간까지는 쓰실 수 있습니다.**
③ 해지 후에는 다음 결제가 이루어지지 않습니다.

## 제8조 (요금 변경)
① 요금을 올릴 때는 **30일 전**에 알려 드립니다.
② 동의하지 않으시면 그 전에 해지하실 수 있고, 이미 결제한 기간은
   **기존 요금**이 적용됩니다.

