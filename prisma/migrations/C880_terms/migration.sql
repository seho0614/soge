# 제3자 제공 동의 (회원 간)

## 왜 필요한가

소개뱅크는 **사업자끼리 서로를 찾도록 잇는** 서비스입니다.
이어 드리려면 **상대방에게 회원의 정보를 알려야** 합니다.

이 동의는 **그 순간에만** 적용됩니다.

## 제1조 (누구에게)
① 회원이 **소개를 요청한 상대방**
② 회원을 **소개받은 상대방**

## 제2조 (무엇을)

### 소개가 성립하기 전
```
상호 · 업종 · 지역 (대략)
```
**연락처와 대표자 이름은 아직 알려 드리지 않습니다.**

### 양쪽이 소개에 동의한 뒤
```
상호 · 대표자 이름 · 연락처 · 주소
사업자등록번호 (계약이 필요한 경우)
```

## 제3조 (왜)
```
거래 상대를 확인하기 위해
연락하고 계약하기 위해
세금계산서를 주고받기 위해
```

## 제4조 (얼마나)
① 제공받은 쪽은 **그 거래가 끝날 때까지** 쓸 수 있습니다.
② 거래가 끝난 뒤에는 **법령이 정한 보관 기간**(계약 기록 5년)이
   지나면 지워야 합니다.

## 제5조 (동의를 거부할 권리)
① 이 동의는 **거부하실 수 있습니다.**
② 다만 동의하지 않으시면 **소개를 주고받을 수 없습니다.** 상대를
   알려 드릴 수 없기 때문입니다.
③ 서비스의 다른 기능(둘러보기 · 커뮤니티 · 건강몰)은 그대로
   쓰실 수 있습니다.

## 제6조 (목적 밖 사용 금지)
제공받은 정보를 **거래 목적 밖으로 쓰는 것**은 금지되며,
개인정보 보호법 위반입니다.

```
광고 발송 · 명단 판매 · 다른 사업에 활용
```

이런 사실을 아시면 회사에 신고해 주십시오. 확인 후 이용 제한
조치를 합니다.

## 제7조 (회사의 역할)
회사는 **정보를 전달할 뿐** 제공받은 쪽이 그것을 어떻게 쓰는지
통제하지 않습니다. 다만 신고가 들어오면 조사하고 조치합니다.

