**하자 · 배송 · 반품 · 환불 책임이 회사에 있습니다.**

## 제1조 (판매자)
```
(주)한국바이오헬스케어 소개뱅크 사업부
대표 노명석 · 사업자등록번호 429-88-01533
```

## 제2조 (청약철회)
① 받으신 날부터 **7일 안**이면 이유를 묻지 않습니다
   (전자상거래법 17조).
② 다만 다음은 철회할 수 없습니다.

```
개봉하신 식품 · 건강기능식품
회원의 요청으로 따로 만든 것
시간이 지나 다시 팔기 어려운 것
```

③ **개봉 여부의 판단은 회사가 합니다.** 다투실 경우 사진 등
