miss AS (
  SELECT a.*, sum(char_length(a.heading) + char_length(a.body) + 7) OVER (ORDER BY a.ord) AS run
    FROM add_rows a, cur c
   WHERE position('### ' || a.heading IN c.body) = 0
),
room AS (
  /* 구분 줄(---)과 묶음 제목 줄 몫을 먼저 뺀 남는 자리 */
  SELECT 20000 - char_length(rtrim(c.body, E'\n')) - 7 - (char_length('## 10. 새로 생긴 기능(2026-11)') + 7) AS n
    FROM cur c
),
fit AS (
  SELECT m.* FROM miss m, room r WHERE m.run <= r.n
),
add_text AS (
  SELECT CASE WHEN count(*) = 0 THEN NULL
              ELSE '## 10. 새로 생긴 기능(2026-11)' || E'\n\n' || string_agg('### ' || heading || E'\n' || body, E'\n\n' ORDER BY ord)
         END AS t
    FROM fit
)
