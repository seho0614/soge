/**
 * 시 · 도 이름을 한 가지로 맞춥니다 (D018 · 2026-10-02).
 *
 * 상담 신청의 지역과 업체의 활동 지역을 **글자 그대로** 비교합니다(fn_lead_candidates).
 * 한쪽이 「서울특별시」, 다른 쪽이 「서울」이면 같은 곳인데도 「받을 업체 없음」이 됩니다 —
 * 1곳에만 보내는 구조에서는 그대로 신청이 버려집니다. 그래서 저장할 때 양쪽 모두 짧은 이름으로 맞춥니다.
 * 17개 시 · 도가 아니면(시험용 이름 등) 그대로 둡니다.
 */
const SHORT: Array<[RegExp, string]> = [
  [/^서울/, '서울'], [/^부산/, '부산'], [/^대구/, '대구'], [/^인천/, '인천'], [/^광주/, '광주'],
  [/^대전/, '대전'], [/^울산/, '울산'], [/^세종/, '세종'], [/^경기/, '경기'], [/^강원/, '강원'],
  [/^(충북|충청북)/, '충북'], [/^(충남|충청남)/, '충남'], [/^(전북|전라북)/, '전북'], [/^(전남|전라남)/, '전남'],
  [/^(경북|경상북)/, '경북'], [/^(경남|경상남)/, '경남'], [/^제주/, '제주'],
];

export function normSido(v: string | null | undefined): string {
  const s = (v ?? '').replace(/\s+/g, '');
  for (const [re, short] of SHORT) if (re.test(s)) return short;
  return (v ?? '').trim();
}
