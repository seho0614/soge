"""v10.25 의 이름 규칙 — 앞 판(v10.24 까지)의 시안 글자에 입혀, 이름 말고 달라진 것만 견주게 합니다.

  10/7 결정: 메뉴 이름 「소개뱅크몰」→「소개몰」 · 옛 이름(소개머니 · 건강몰 · 옛 뜻의 소개몰)도 약관까지 같이 고침.
  순서가 중요합니다 — 「소개몰」은 2026-09-26 까지 안심소개의 이름이었으므로 그 뜻의 글을 먼저 「안심소개」로 바꾼 뒤 새 이름을 넣습니다
  (qa/apply_proto_v1025.py 의 0절과 같은 규칙).
     ① 옛 「소개몰」(= 안심소개) → 안심소개   ② 소개머니 → 소개장터   ③ 건강몰 → 소개몰   ④ 소개뱅크몰 → 소개몰
"""
import re
_KEEP = '(그림은 「소개몰」)'      # 제시 디자인의 메뉴 글자를 말하는 곳 — 그대로 둡니다


def names(t):
    if not isinstance(t, str): return t
    t = t.replace(_KEEP, '\x00K')
    t = re.sub(r'(?<!뱅크)소개몰', '안심소개', t).replace('소개머니', '소개장터').replace('건강몰', '소개몰').replace('소개뱅크몰', '소개몰')
    return t.replace('\x00K', _KEEP)
